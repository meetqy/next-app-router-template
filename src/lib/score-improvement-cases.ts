export function getScoreImprovementCase(slug: string) {
	return SCORE_IMPROVEMENT_CASES.find((item) => item.slug === slug) ?? null;
}

export function getScoreImprovementCaseSiblings(slug: string) {
	const index = SCORE_IMPROVEMENT_CASES.findIndex((item) => item.slug === slug);

	return {
		next:
			index >= 0 && index < SCORE_IMPROVEMENT_CASES.length - 1
				? SCORE_IMPROVEMENT_CASES[index + 1]
				: null,
		previous: index > 0 ? SCORE_IMPROVEMENT_CASES[index - 1] : null,
	};
}

export function getRelatedScoreImprovementCases(slug: string, limit = 9) {
	return SCORE_IMPROVEMENT_CASES.filter((item) => item.slug !== slug).slice(
		0,
		limit,
	);
}
